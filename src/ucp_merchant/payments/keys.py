"""ECDSA P-256 key management for AP2 payment mandates.

The merchant only ever needs *public* keys.  An agent signs mandates with a
private key that it keeps to itself and registers the matching public key
(as a JWK) with :meth:`KeyManager.register_public_key`.  Signature
verification then runs against that registered public key.

Keys generated by :meth:`KeyManager.generate_key_pair` exist only for the demo
endpoints (see ``AP2_DEMO_MODE``): the server keeps the private half in memory
so it can sign example mandates on the agent's behalf.  Keys registered by an
agent never have a private half on the server.
"""

from __future__ import annotations

import base64
import binascii
import hashlib
import json
from typing import Any

import structlog
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.serialization import (
    Encoding,
    NoEncryption,
    PrivateFormat,
    PublicFormat,
)

from ucp_merchant.models import KeyPairInfo
from ucp_merchant.utils import utcnow

logger = structlog.get_logger(__name__)

_P256_COORDINATE_BYTES = 32


class InvalidKeyError(ValueError):
    """Raised when a submitted JWK is not an acceptable P-256 public key."""


def _int_to_base64url(value: int, length: int) -> str:
    """Encode a positive integer as an unpadded base64url string."""
    raw = value.to_bytes(length, byteorder="big")
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode("ascii")


def _base64url_to_bytes(value: str) -> bytes:
    """Decode an (optionally unpadded) base64url string."""
    try:
        return base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))
    except (binascii.Error, ValueError) as exc:
        raise InvalidKeyError("JWK coordinates must be base64url encoded") from exc


def jwk_thumbprint(jwk: dict[str, Any]) -> str:
    """Return the RFC 7638 SHA-256 thumbprint of an EC public JWK."""
    canonical = json.dumps(
        {"crv": jwk["crv"], "kty": jwk["kty"], "x": jwk["x"], "y": jwk["y"]},
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    digest = hashlib.sha256(canonical).digest()
    return base64.urlsafe_b64encode(digest).rstrip(b"=").decode("ascii")


class KeyManager:
    """In-memory store of ECDSA P-256 *public* keys.

    Key IDs are derived from the RFC 7638 JWK thumbprint, so registering the
    same public key twice is idempotent and an ID can never be claimed for a
    different key.
    """

    def __init__(self) -> None:
        self._public_keys: dict[str, ec.EllipticCurvePublicKey] = {}
        self._info: dict[str, KeyPairInfo] = {}
        # Only populated for demo keys created by generate_key_pair().
        self._demo_private_keys: dict[str, ec.EllipticCurvePrivateKey] = {}

    # -- registration --------------------------------------------------------

    def register_public_key(self, jwk: dict[str, Any]) -> KeyPairInfo:
        """Register an agent's public key.

        Parameters
        ----------
        jwk:
            An EC / P-256 public JWK.  A JWK that carries private key
            material (``d``) is rejected so a private key can never be
            uploaded to the merchant by mistake.

        Raises
        ------
        InvalidKeyError
            If the JWK is malformed, is not P-256, contains private
            material, or its point is not on the curve.
        """
        public_key = self._public_key_from_jwk(jwk)
        public_jwk = self._export_jwk(public_key)
        key_id = f"jkt_{jwk_thumbprint(public_jwk)}"

        existing = self._info.get(key_id)
        if existing is not None:
            return existing

        public_jwk["kid"] = key_id
        info = KeyPairInfo(
            key_id=key_id,
            algorithm="ES256",
            curve="P-256",
            created_at=utcnow(),
            public_key_jwk=public_jwk,
        )
        self._public_keys[key_id] = public_key
        self._info[key_id] = info
        logger.info("public_key_registered", key_id=key_id)
        return info

    def generate_key_pair(self) -> KeyPairInfo:
        """Generate a *demo* key pair, keeping the private half in memory.

        Only the demo endpoints use this.  Real agents generate their own
        keys and call :meth:`register_public_key`.
        """
        private_key = ec.generate_private_key(ec.SECP256R1())
        info = self.register_public_key(self._export_jwk(private_key.public_key()))
        self._demo_private_keys[info.key_id] = private_key
        logger.info("demo_key_pair_generated", key_id=info.key_id)
        return info

    # -- lookup --------------------------------------------------------------

    def get_public_key(self, key_id: str) -> ec.EllipticCurvePublicKey:
        """Return the registered public key for *key_id*.

        Raises
        ------
        KeyError
            If *key_id* has not been registered.
        """
        key = self._public_keys.get(key_id)
        if key is None:
            raise KeyError(f"Key not found: {key_id!r}")
        return key

    def get_public_key_jwk(self, key_id: str) -> dict[str, str]:
        """Export the public key for *key_id* as a JWK dict."""
        jwk = self._export_jwk(self.get_public_key(key_id))
        jwk["kid"] = key_id
        return jwk

    def get_public_key_pem(self, key_id: str) -> str:
        """Export the public key for *key_id* in PEM format."""
        pem_bytes = self.get_public_key(key_id).public_bytes(
            encoding=Encoding.PEM,
            format=PublicFormat.SubjectPublicKeyInfo,
        )
        return pem_bytes.decode("ascii")

    def get_key_info(self, key_id: str) -> KeyPairInfo:
        """Return metadata about a registered key."""
        info = self._info.get(key_id)
        if info is None:
            raise KeyError(f"Key not found: {key_id!r}")
        return info

    def list_keys(self) -> list[KeyPairInfo]:
        """Return metadata for all registered keys."""
        return list(self._info.values())

    # -- demo-only private key access ---------------------------------------

    def get_private_key(self, key_id: str) -> ec.EllipticCurvePrivateKey:
        """Return the private key of a *demo* key pair, for signing.

        Raises
        ------
        KeyError
            If *key_id* is not a demo key held by this server.  Keys that an
            agent registered have no private half here, by design.
        """
        key = self._demo_private_keys.get(key_id)
        if key is None:
            raise KeyError(f"No demo private key held for: {key_id!r}")
        return key

    def export_private_key_pem(self, key_id: str) -> str:
        """Export a demo private key in PEM format (test/demo only)."""
        pem_bytes = self.get_private_key(key_id).private_bytes(
            encoding=Encoding.PEM,
            format=PrivateFormat.PKCS8,
            encryption_algorithm=NoEncryption(),
        )
        return pem_bytes.decode("ascii")

    # -- private helpers -----------------------------------------------------

    @staticmethod
    def _public_key_from_jwk(jwk: dict[str, Any]) -> ec.EllipticCurvePublicKey:
        if not isinstance(jwk, dict):
            raise InvalidKeyError("JWK must be a JSON object")
        if "d" in jwk:
            raise InvalidKeyError(
                "JWK contains private key material ('d'); register the public key only"
            )
        if jwk.get("kty") != "EC" or jwk.get("crv") != "P-256":
            raise InvalidKeyError("Only EC keys on curve P-256 are supported")
        if jwk.get("alg") not in (None, "ES256"):
            raise InvalidKeyError("JWK 'alg' must be ES256 when present")
        if jwk.get("use") not in (None, "sig"):
            raise InvalidKeyError("JWK 'use' must be 'sig' when present")

        coordinates: list[int] = []
        for name in ("x", "y"):
            value = jwk.get(name)
            if not isinstance(value, str):
                raise InvalidKeyError(f"JWK is missing coordinate {name!r}")
            raw = _base64url_to_bytes(value)
            if len(raw) != _P256_COORDINATE_BYTES:
                raise InvalidKeyError(f"JWK coordinate {name!r} must be 32 bytes")
            coordinates.append(int.from_bytes(raw, "big"))

        try:
            numbers = ec.EllipticCurvePublicNumbers(coordinates[0], coordinates[1], ec.SECP256R1())
            return numbers.public_key()
        except ValueError as exc:
            raise InvalidKeyError("JWK point is not on curve P-256") from exc

    @staticmethod
    def _export_jwk(public_key: ec.EllipticCurvePublicKey) -> dict[str, str]:
        """Build a JWK dict from an ECDSA P-256 public key."""
        numbers = public_key.public_numbers()
        return {
            "kty": "EC",
            "crv": "P-256",
            "x": _int_to_base64url(numbers.x, _P256_COORDINATE_BYTES),
            "y": _int_to_base64url(numbers.y, _P256_COORDINATE_BYTES),
            "use": "sig",
            "alg": "ES256",
        }
